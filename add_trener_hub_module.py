def new_slug(existing):
    slug = uuid.uuid4().hex[:8]
    while slug in existing:
        slug = uuid.uuid4().hex[:8]
    return slug


def main():
    pages = github_store.pages_store.load()
    max_order = max((p["course_order"] for p in pages.values() if p.get("course_order") is not None), default=0)
    added = []
    for i, lesson in enumerate(LESSONS, start=1):
        slug = new_slug(pages)
        pages[slug] = {
            "title": lesson["title"],
            "html": lesson["html"],
            "course_order": max_order + i,
            "plan_day": None,  # не часть обязательного расписания онбординга
            "module": MODULE,
            "category": None,
            "quiz": lesson["quiz"],
            "tags": ["тренер хаб"],
            "review_by": None,
            "updated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "updated_by": "автосохранение",
        }
        added.append((slug, lesson["title"]))
    github_store.pages_store.save(pages, f"курс: добавлен модуль «{MODULE}» ({len(added)} уроков, скрыт по умолчанию)")
    for slug, title in added:
        print(slug, "-", title)


if __name__ == "__main__":
    main()
